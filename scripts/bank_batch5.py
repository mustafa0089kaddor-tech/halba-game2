def _parse(raw):
    out={}
    for slug,block in raw.items():
        qs=[]
        for line in block.strip().splitlines():
            line=line.strip()
            if not line: continue
            f=[x.strip() for x in line.split('|')]
            assert len(f) in (6,7), (slug,line)
            qs.append(Q(int(f[0]),f[1],f[2],f[3:6],(f[6] or None) if len(f)==7 else None))
        out[slug]=qs
    return out

