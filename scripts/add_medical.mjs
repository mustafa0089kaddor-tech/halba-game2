async function run() {
  // 1. تحديث src/data/catalog.ts
  const catFile = fs.readFileSync(CATALOG_PATH, 'utf8');
  const groupsMatch = catFile.match(/export const GROUPS\s*=\s*(\[[\s\S]*?\])\s*as const;/);
  const catalogMatch = catFile.match(/export const CATALOG[^=]*=\s*(\[[\s\S]*?\]);/);

  if (!groupsMatch || !catalogMatch) {
    console.error('❌ تعذر قراءة ملف catalog.ts.');
    process.exit(1);
  }

  let groups = new Function(`return ${groupsMatch[1]}`)();
  let catalog = new Function(`return ${catalogMatch[1]}`)();

  groups = groups.filter(g => g.key !== 'medical');
  groups.push(MEDICAL_GROUP);

  const medSlugs = new Set(MEDICAL_CATEGORIES.map(c => c.slug));
  catalog = catalog.filter(c => c.group !== 'medical' && !medSlugs.has(c.slug));

  const baseSort = catalog.reduce((max, c) => Math.max(max, c.sort || 0), 120);
  MEDICAL_CATEGORIES.forEach((mc, i) => {
    catalog.push({
      slug: mc.slug,
      name: mc.name,
      emoji: mc.emoji,
      color: MEDICAL_GROUP.color,
      group: MEDICAL_GROUP.key,
      sort: baseSort + i + 1,
      description: `أسئلة متنوعة عن ${mc.name} ضمن «${MEDICAL_GROUP.name}»، بثلاثة مستويات: ٢٠٠ و٤٠٠ و٦٠٠ نقطة.`
    });
  });

  const newCatalogTs = `// generated by scripts/gen_data.py + add_medical.mjs\nexport const GROUPS = ${JSON.stringify(groups, null, 1)} as const;\nexport const CATALOG: { slug: string; name: string; emoji: string; color: string; group: string; sort: number; description: string }[] = ${JSON.stringify(catalog, null, 1)};\n`;
  fs.writeFileSync(CATALOG_PATH, newCatalogTs, 'utf8');
  console.log(`✅ تم تحديث catalog.ts: إضافة محور «${MEDICAL_GROUP.name}» مع ${MEDICAL_CATEGORIES.length} فئة طبية.`);

  // 2. قراءة وتحديث src/data/bank.ts
  const bankContent = fs.readFileSync(BANK_PATH, 'utf8');
  const marker = 'export const BANK: BankQuestion[] = [';
  const startIdx = bankContent.indexOf(marker);
  const header = bankContent.slice(0, startIdx + marker.length);
  const arrayText = bankContent.slice(startIdx + marker.length - 1).trim().replace(/;\s*$/, '');
  let questions = new Function(`return ${arrayText}`)();

  // إزالة أي نسخة سابقة من الأسئلة الطبية لمنع التكرار
  questions = questions.filter(q => !medSlugs.has(q.cat));

  // سحب صور ويكيميديا كومنز للأسئلة الطبية
  const cleanAnswer = (ans) => ans.replace(/\s*\(.*?\)\s*/g, '').trim();
  const arTitles = [];
  Object.values(RAW_QUESTIONS).flat().forEach(row => arTitles.push(cleanAnswer(row[2])));
  const enTopics = MEDICAL_CATEGORIES.flatMap(c => c.topics);

  console.log('🌐 جاري سحب الصور الطبية من ويكيميديا كومنز...');
  const [arThumbs, enThumbs] = await Promise.all([
    fetchWikiThumbnails(arTitles, 'ar'),
    fetchWikiThumbnails(enTopics, 'en')
  ]);

  let addedCount = 0;
  MEDICAL_CATEGORIES.forEach(mc => {
    const rows = RAW_QUESTIONS[mc.slug] || [];
    const catThumbs = mc.topics.map(t => enThumbs[t]).filter(Boolean);

    rows.forEach((r, idx) => {
      const [points, question, answer, w1, w2, w3] = r;
      const cleaned = cleanAnswer(answer);
      let chosenUrl = arThumbs[cleaned] || (catThumbs.length > 0 ? catThumbs[idx % catThumbs.length] : null);
      let credit = 'الصورة: ويكيميديا كومنز — رخصة المشاع الإبداعي (CC BY-SA 4.0)';
      let license = 'free';

      if (!chosenUrl) {
        chosenUrl = ensureLocalMedSvg(mc.slug, mc.name, mc.emoji, idx);
        credit = 'تصميم حلبة الطبي التفاعلي';
        license = 'own';
      }

      questions.push({
        id: `${mc.slug}-${idx}`,
        cat: mc.slug,
        points,
        type: 'image',
        question,
        answer,
        options: [answer, w1, w2, w3],
        source: 'المراجع الطبية المعتمدة (Harrison\'s & UpToDate)',
        sourceUrl: null,
        flags: [],
        mediaType: 'image',
        imageUrl: chosenUrl,
        mediaCredit: credit,
        mediaLicense: license
      });
      addedCount++;
    });
  });

  const formattedLines = questions.map(q => '  ' + JSON.stringify(q) + ',');
  const finalBank = `${header}\n${formattedLines.join('\n')}\n];\n`;
  fs.writeFileSync(BANK_PATH, finalBank, 'utf8');

  console.log(`✅ اكتمل بنجاح! تم إضافة ${MEDICAL_CATEGORIES.length} فئة طبية و ${addedCount} سؤالاً طبياً مدعوماً بالصور إلى bank.ts.`);
}

run();
